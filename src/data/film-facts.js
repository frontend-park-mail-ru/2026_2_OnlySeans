for (const group of VERSION_GROUPS) for (const entry of group) if (entry.id) VERSIONS.set(entry.id, group);

const MONTHS = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
const MONTHS_NOMINATIVE = ['январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'];

/** «10 сентября 1994», «май 1987» или «1980». */
export const formatPremiere = value => {
  const [year, month, day] = String(value || '').split('-').map(Number);
  if (!year) return '';
  if (!month) return String(year);
  if (!day) return `${MONTHS_NOMINATIVE[month - 1]} ${year}`;
  return `${day} ${MONTHS[month - 1]} ${year}`;
};

/** Сведения о фильме: премьеры, сценаристы, английское название. null — нет данных. */
export const getFilmFacts = movie => {
  const raw = FACTS[movie?.id];
  const english = movie?.englishTitle && movie.englishTitle !== movie.title ? movie.englishTitle : ENGLISH_TITLES[movie?.id] || '';
  if (!raw) return english ? { worldPremiere: '', russiaPremiere: '', russiaLabel: 'в России', writers: [], englishTitle: english } : null;
  const [world, russia, writers] = raw;
  return {
    worldPremiere: world,
    russiaPremiere: russia.replace('!', ''),
    russiaLabel: russia.endsWith('!') ? 'в СССР' : 'в России',
    writers: writers ? writers.split('|') : [],
    englishTitle: english,
  };
};

/** Все версии истории, к которой относится фильм (включая его самого), по годам. [] — версий нет. */
export const getFilmVersions = (movie, catalog = []) => {
  const group = VERSIONS.get(movie?.id);
  if (!group) return [];
  const byId = new Map(catalog.map(item => [item.id, item]));
  return group.map(entry => {
    if (!entry.id) return { ...entry, current: false };
    const film = entry.id === movie.id ? movie : byId.get(entry.id);
    return film ? { id: film.id, title: film.title, year: film.year, note: entry.note || '', movie: film, current: film.id === movie.id } : null;
  }).filter(Boolean).sort((a, b) => a.year - b.year || Number(a.current) - Number(b.current));
};
